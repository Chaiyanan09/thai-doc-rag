    /** system prompt ของรุ่นที่เป็นค่าเริ่มต้น */
    public static final String SYSTEM_PROMPT = PROMPTS.get(DEFAULT_PROMPT_VERSION);

    public static Set<String> versions() {
        return new TreeSet<>(PROMPTS.keySet());
    }

    public static String systemPrompt(String version) {
        String prompt = PROMPTS.get(version == null ? DEFAULT_PROMPT_VERSION : version.strip().toLowerCase());
        if (prompt == null) {
            throw new IllegalArgumentException("ไม่รู้จัก prompt รุ่น '" + version + "' ใช้ได้: " + versions());
        }
        return prompt;
    }

