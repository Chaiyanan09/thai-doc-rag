from app.pdf_reader import _Block, _paragraphs


def line(x0: float, y0: float, x1: float, text: str) -> _Block:
    """block 1 บรรทัด สูง 14 จุด (แบบ PDF ที่ export จาก Chrome ซึ่งเก็บ 1 บรรทัดเป็น 1 block)"""
    return _Block(x0, y0, x1, y0 + 14, text, 1)


def test_wrapped_lines_are_joined_back_into_one_paragraph():
    blocks = [
        line(92, 100, 520, "ข้อ 16 นักศึกษาต้องชำระค่ารักษาสภาพนักศึกษาภาคการ"),  # บรรทัดแรกย่อหน้าเข้าไป ยาวเต็ม
        line(68, 119, 500, "ศึกษาละ 1,000 บาท ภายในสองสัปดาห์แรก"),  # ต่อที่ขอบซ้าย
        line(92, 140, 300, "ข้อ 17 ระยะเวลาที่ลาพัก"),  # ย่อหน้าเข้าไป = ย่อหน้าใหม่
    ]

    assert _paragraphs(blocks) == [
        "ข้อ 16 นักศึกษาต้องชำระค่ารักษาสภาพนักศึกษาภาคการศึกษาละ 1,000 บาท ภายในสองสัปดาห์แรก",
        "ข้อ 17 ระยะเวลาที่ลาพัก",
    ]


def test_short_line_ends_paragraph_and_table_cells_stay_on_one_row():
    blocks = [
        line(68, 100, 200, "(5) ลาออก"),  # บรรทัดสั้น = จบย่อหน้า
        line(68, 119, 520, "ข้อ 23 นักศึกษาที่ทุจริตในการสอบ"),
        line(68, 160, 90, "A"),  # ห่างเกินหนึ่งบรรทัด = ย่อหน้าใหม่
        line(150, 160, 200, "ดีเยี่ยม"),  # บรรทัดเดียวกัน = ช่องในตาราง
        line(300, 160, 320, "4.0"),
    ]

    assert _paragraphs(blocks) == ["(5) ลาออก", "ข้อ 23 นักศึกษาที่ทุจริตในการสอบ", "A ดีเยี่ยม 4.0"]
